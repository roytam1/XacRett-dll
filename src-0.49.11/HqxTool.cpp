static WORD crc;
static void update_crc(int c)
{
	DWORD temp=crc;
	for( int i=0; i!=8; i++ )
	{
		c <<= 1;
		if( (temp<<=1) & 0x10000 )
			temp = (temp & 0xffff) ^ 0x1021;
		temp ^= (c >> 8);
		c &= 0xff;
	}
	crc = (WORD)temp;
}

