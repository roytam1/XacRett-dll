bool CHqxTool::FindBeginning(int limit)
{
	int ct=0;
	char str[5000];
	while( !feof(fp) && (ct++)!=limit )
	{
		kiutil::getline( str,sizeof(str),fp );
		if( 0==strcmp(str,"(This file must be converted with BinHex 4.0)") )
			return true;
		if( 0==strcmp(str,"（このファイルは BinHex4.0 で変換される必要があります。）") )
			return true;
	}
	return false;
}

bool CHqxTool::ProcessHeader()
{
	int j;

	bStarted = false;
	bEOF     = false;
	repeating= 0;
	prevc    = -1;
	crc      = 0;
	outbuf   = i = 0;

	// ファイル名
	int fnlen = GetByte();
	if( fnlen == -1 )
		return false;
	for( j=0; j!=fnlen; j++ )
		outname[j] = GetByte();
	outname[j]=0;
	// 11bytesスキップ
	for( j=0; j!=11; j++ )
		GetByte();
	// ファイルサイズ
	fsize = ((DWORD)GetByte()<<24)|((DWORD)GetByte()<<16)|((DWORD)GetByte()<<8)|((DWORD)GetByte());
	// 4bytesスキップ
	for( j=0; j!=4; j++ )
		GetByte();
	// CRC計算
	update_crc(0), update_crc(0);
	WORD r_crc=crc;
	// ヘッダのCRC
	WORD h_crc=((WORD)GetByte()<<8)|((WORD)GetByte());

	// 判定
	return ( r_crc==h_crc && !bEOF );
}

void CHqxTool::DoDataFork()
{
	int c;
	while( fsize-- )
	{
		c = GetByte();
		if( c==-1 )
			break;
		fputc( c, op );
	}
}

