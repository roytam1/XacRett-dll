bool CHqxTool::Check( const char* fname, unsigned long fsize )
{
	if( !(fp=fopen(fname,"rb")) )
		return false;

	bool ans = FindBeginning(500) ? ProcessHeader() : false;

	fclose( fp );
	return ans;
}

bool CHqxTool::Extract( const char* fname,const char* ddir )
{
	if( !(fp=fopen(fname,"rb")) )
		return false;

	if( !(FindBeginning(-1) ? ProcessHeader() : false) )
	{
		fclose( fp );
		return false;
	}

	if (m_Endflg) return true;//追加 By Bonty
	//ワイルドカード処理
	if (!CheckStr(outname)){fclose(fp);return true;}//追加 By Bonty

	if( !(op=fopen(kiutil::pathMake(outname),"wb")) )
	{
		fclose(fp);
		return false;
	}

	DoDataFork();

	fclose(op), fclose(fp);
	return true;
}
