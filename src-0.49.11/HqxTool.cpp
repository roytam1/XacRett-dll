int CHqxTool::GetByteRaw()
{
	if( bEOF )return -1;
	int c=fgetc(fp);

	if( c==-1 )
		c=':';

	if( !bStarted && c==':' )
	{	bStarted=true;return GetByteRaw();	}
	else if( bStarted && c==':' )
	{	bEOF=true;return -1;	}
	else if( 0xff==hqx[c] )
	{	return GetByteRaw();	}

	switch( i )
	{
	case 0:
		outbuf = hqx[c]<<18;
		i=1;
		return GetByteRaw();
	case 1:
		outbuf |= hqx[c]<<12;
		i=2;
		return (outbuf>>16);
	case 2:
		outbuf |= hqx[c]<<6;
		i=3;
		return ((outbuf>>8)&0xff);
	default:
	case 3:
		outbuf |= hqx[c];
		i=0;
		return (outbuf&0xff);
	}
}

int CHqxTool::GetByte()
{
	if( repeating!=0 )
	{
		repeating--;
		update_crc( prevc );
		return prevc;
	}

	int c = GetByteRaw();
	if( c==-1 )
		return -1;
	else if( c==0x90 )
	{
		c = GetByteRaw();
		if( c==-1 )
			return -1;
		else if( c==0 )
		{
			update_crc( prevc=0x90 );
			return 0x90;
		}

		repeating = c-1;
		return GetByte();
	}

	update_crc( prevc=c );
	return c;
}

