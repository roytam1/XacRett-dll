int COpenHqx::GetByteRaw()
{
	if( bEOF )return -1;
	int c=fgetc(fp);

	if( c==-1 )
		c=':';

	if( !bStarted && c==':' )
	{	bStarted=true;return GetByteRaw();	}
	else if( bStarted && c==':' )
	{	bEOF=true;return -1;	}
	else if( 0xff==hqx[c] )
	{	return GetByteRaw();	}

	switch( i )
	{
	case 0:
		outbuf = hqx[c]<<18;
		i=1;
		return GetByteRaw();
	case 1:
		outbuf |= hqx[c]<<12;
		i=2;
		return (outbuf>>16);
	case 2:
		outbuf |= hqx[c]<<6;
		i=3;
		return ((outbuf>>8)&0xff);
	default:
	case 3:
		outbuf |= hqx[c];
		i=0;
		return (outbuf&0xff);
	}
}

int COpenHqx::GetByte()
{
	if( repeating!=0 )
	{
		repeating--;
		update_crc( prevc );
		return prevc;
	}

	int c = GetByteRaw();
	if( c==-1 )
		return -1;
	else if( c==0x90 )
	{
		c = GetByteRaw();
		if( c==-1 )
			return -1;
		else if( c==0 )
		{
			update_crc( prevc=0x90 );
			return 0x90;
		}

		repeating = c-1;
		return GetByte();
	}

	update_crc( prevc=c );
	return c;
}

bool COpenHqx::FindBeginning(int limit)
{
	int ct=0;
	char str[5000];
	while( !feof(fp) && (ct++)!=limit )
	{
		kiutil::getline( str,sizeof(str),fp );
		if( 0==strcmp(str,"(This file must be converted with BinHex 4.0)") )
			return true;
		if( 0==strcmp(str,"（このファイルは BinHex4.0 で変換される必要があります。）") )
			return true;
	}
	return false;
}

bool COpenHqx::ProcessHeader()
{
	int j;

	bStarted = false;
	bEOF     = false;
	repeating= 0;
	prevc    = -1;
	crc      = 0;
	outbuf   = i = 0;

	// ファイル名
	int fnlen = GetByte();
	if( fnlen == -1 )
		return false;
	for( j=0; j!=fnlen; j++ )
		outname[j] = GetByte();
	outname[j]=0;
	// 11bytesスキップ
	for( j=0; j!=11; j++ )
		GetByte();
	// ファイルサイズ
	fsize = ((DWORD)GetByte()<<24)|((DWORD)GetByte()<<16)|((DWORD)GetByte()<<8)|((DWORD)GetByte());
	// 4bytesスキップ
	for( j=0; j!=4; j++ )
		GetByte();
	// CRC計算
	update_crc(0), update_crc(0);
	WORD r_crc=crc;
	// ヘッダのCRC
	WORD h_crc=((WORD)GetByte()<<8)|((WORD)GetByte());

	// 判定
	return ( r_crc==h_crc && !bEOF );
}