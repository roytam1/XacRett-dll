int COpenIsh::decode_jis8(BYTE* str,int len,BYTE* outbuf)
{
	len=(len>79)?79:len;
	BYTE* start=outbuf;

	outbuf--;
	for( int i=0,j,c; i<len; ++i )
	{
		if( (c=j8table[str[i]])==0xff )
			return 0;
		if( j=(i&7) )
			*outbuf |= c<<(8-j);
		if( j!=7 )
			*++outbuf = c>>j;
	}

	return outbuf-start;
}

int COpenIsh::decode_jis7(BYTE* str,int len,BYTE* outbuf)
{
	len=(len>78)?78:len;
	BYTE* start=outbuf;

	int c,c1,c2,c3;
	if( (c =j7table[str[0]])==0xff )	return 0;
	if( (c1=j7table[str[1]])==0xff )	return 0;
	if( (c2=j7table[str[2]])==0xff )	return 0;
	if( (c3=j7table[str[3]])==0xff )	return 0;
	*outbuf++ = c1<<6 | c;
	*outbuf++ = c2<<4 | c1>> 2;
	*outbuf   = c3<<2 | c2>> 4;

	for( int i=0,k=4,j,d; k<len; ++i )
	{
		if( (c1=j7table[str[k++]])==0xff )	return 0;
		if( (c2=j7table[str[k++]])==0xff )	return 0;

		d = c1*91 + c2;
		if( d>0x3fff )return 0;

		if( (j=dj7_m[i & (8-1)]) != 0)
			*outbuf |= d<<(8-j)&0xff;
		*++outbuf = d>>j;
		if( j<5 )
			*++outbuf = d>>(8+j);
    }

	return outbuf-start;
}