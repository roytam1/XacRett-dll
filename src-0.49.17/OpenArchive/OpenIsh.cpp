bool COpenIsh::FindFirst(INDIVIDUALINFO *lpSubInfo)
{
	readsize=0;
	
	return Find_sub(lpSubInfo);
}

bool COpenIsh::FindNext(INDIVIDUALINFO *lpSubInfo)
{
	return Find_sub(lpSubInfo);
}

bool COpenIsh::Find_sub(INDIVIDUALINFO *lpSubInfo)
{
	if(!FindHeader())
		return false;
	Skip();
	lpSubInfo->dwCompressedSize=(DWORD)(ftell(COpenIsh::fp)-readsize);
	lpSubInfo->dwCRC= h_FCRC32;
	lpSubInfo->dwOriginalSize=h_FLen;
	lstrcpy(lpSubInfo->szFileName,*h_LFN==0?h_FName:h_LFN);

	lpSubInfo->wDate=(WORD)(h_LcTime>>16);
	lpSubInfo->wTime=(WORD)h_LcTime;
	lstrcpy(lpSubInfo->szAttribute,"A---W");

	double tmp1 = (double)lpSubInfo->dwOriginalSize;
	double tmp2 = (double)lpSubInfo->dwCompressedSize;
	if (lpSubInfo->dwOriginalSize > 0 && lpSubInfo->dwCompressedSize > 0){
		lpSubInfo->wRatio = (WORD)((tmp2 *1000 / tmp1));
	}

	readsize+=lpSubInfo->dwCompressedSize;

	//lstrcpy(lpSubInfo->szMode,"");
	return true;
}

// ヘッダ行を見つけてその情報を取得
bool COpenIsh::FindHeader(bool bfirst)
{
	char str[100],str2[100],str3[100];
	if( bfirst )*h_LFN=0;

	while( NULL!=kiutil::getline(str,100,COpenIsh::fp) )
	{
		switch( *str )
		{
		case '<':
			if( bfirst && strncmp(str,"<<< ",4)==0 && strstr(str," aish ") && strstr(str," lines") )
			{
				char *s,*p;
				for(s=h_LFN,p=str+4; *p!=' '; *s++=*p++ );
				*s=0;
			}
			break;
		case '!':
		case '#':
			{
				if( strlen(str)<=60 )break;
				if( NULL==kiutil::getline(str2,100,COpenIsh::fp) || NULL==kiutil::getline(str3,100,COpenIsh::fp) )
					return false;

				char* line=str;
				if( strcmp(str,str2)!=0 )
				{
					if( strcmp(str,str3)!=0 )
					{
						if( strcmp(str2,str3)!=0 )
							break;
						else
							line=str2;
					}
				}

				BYTE dat[200];
				int l;
				if( *line=='!' )l=decode_jis7((BYTE*)line,strlen(line),dat);
				else			l=decode_jis8((BYTE*)line,strlen(line),dat);
				return ProcessHeader(dat,l,bfirst);
			}
		}
	}
	return false;
}

bool COpenIsh::Skip()
{
	char str[100];

	while( NULL!=kiutil::getline(str,100,COpenIsh::fp) )
	{
		switch( *str )
		{
		case '<':
			break;
		case '!':
		case '#':
			if( strlen(str)<=60 )break;
			return true;
			break;
		}
	}
	return false;
}
// データ列＞ヘッダ情報
bool COpenIsh::ProcessHeader(BYTE* dat,int l,bool bfirst)
{
	if( bfirst )
	{
		h_Mv   = dat[1];
		h_FLen = ((dat[2])|(dat[3]<<8)|(dat[4]<<16)|(dat[5]<<24));
		h_LLen = ((dat[6])|(dat[7]<<8));
		h_LNum = ((dat[8])|(dat[9]<<8));
		h_IType= dat[11];
		int i,j;
		for( i=0; i!=8 && dat[i+12]!=' '; i++ )h_FName[i]=(char)dat[i+12];h_FName[i++]='.';
		for( j=8; j!=11; j++,i++ )h_FName[i]=(char)dat[j+12];h_FName[i]='\0';
		h_bOld = (h_Mv==0)?dat[25]==0:false;
		h_Flag = dat[26];
		h_LcTime=((dat[27])|(dat[28]<<8)|(dat[29]<<16)|(dat[30]<<24));
		h_DifTm= ((dat[31])|(dat[32]<<8)|(dat[33]<<16));
		h_FCRC16=((dat[34])|(dat[35]<<8));
		h_FCRC32=((dat[36])|(dat[37]<<8)|(dat[38]<<16)|(dat[39]<<24));
		h_VLen = ((dat[40])|(dat[41]<<8)|(dat[42]<<16)|(dat[43]<<24));
		h_VCRC16=((dat[44])|(dat[45]<<8));

		if( l==63 )		h_CRC=((dat[61]<<8)|(dat[62]));
		else if( l==69 )h_CRC=((dat[67]<<8)|(dat[68]));
		else			return false;

		if( 62!=h_LNum && 68!=h_LNum && 72!=h_LNum )return false;
		if( 8!=h_IType && 13!=h_IType && 14!=h_IType && 15!=h_IType )return false;

		return h_CRC==(crc16(dat,l-2,0xffff)^0xffff);
	}

	h_Mv   = dat[1];
	h_VLen = ((dat[40])|(dat[41]<<8)|(dat[42]<<16)|(dat[43]<<24));
	WORD tmpCRC;
	if( l==63 )		tmpCRC=((dat[61]<<8)|(dat[62]));
	else if( l==69 )tmpCRC=((dat[67]<<8)|(dat[68]));
	else			return false;

	return tmpCRC==(crc16(dat,l-2,0xffff)^0xffff);
}

