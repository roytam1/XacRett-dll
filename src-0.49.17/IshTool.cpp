bool CIshTool::Extract( const char* fname,const char* ddir )
{
	strcpy( IshName,fname );
	if( !(ish = fopen( fname,"rb" )) )
		return false;

	while( FindHeader() )
	{
		if( h_Mv==0 )
			h_VLen=h_FLen;

		if (m_Endflg) return true;//追加 By Bonty
		//ワイルドカード処理
		if (!CheckStr(*h_LFN==0?h_FName:h_LFN))//追加 By Bonty
		{
blockread2:
			if( h_FLen>=h_VLen )
				h_FLen -= h_VLen;
			else
			{
				h_VLen=h_FLen;
				h_FLen=0;
			}
			while( int l=GetBlockData() )
				for( int i=0; i!=l; i++ );

			if( GetNextVol() )
				goto blockread2;
			continue;
		}

		FILE* out=fopen( kiutil::pathMake(*h_LFN==0?h_FName:h_LFN),"wb" );
		if(out==NULL)//追加 By Bonty
			goto blockread2;

		int l;
blockread:
		if( h_FLen>=h_VLen )
			h_FLen -= h_VLen;
		else
		{
			h_VLen=h_FLen;
			h_FLen=0;
		}

		while( l=GetBlockData() )
			for( int i=0; i!=l; i++ )
				fwrite( block[i],1,blocklen[i],out );
		if( GetNextVol() )
			goto blockread;

		fclose(out);

		if( h_Flag&1 )
			kiutil::timeSet( *h_LFN==0?h_FName:h_LFN,
					(WORD)(h_LcTime>>16),(WORD)h_LcTime );

		if( !ish )
			break;
	}


	if( ish )
		fclose( ish );
	return true;
}

