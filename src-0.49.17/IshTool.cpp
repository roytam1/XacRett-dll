static int decode_sjis(BYTE* str,int len,BYTE* outbuf)
{
	len=(len>78)?78:len;
	BYTE* start=outbuf;

	BYTE c;
	if( (c=j8table[*str])==0xff )return 0;
	*outbuf = c;

	// 15bit decoding
	WORD i,k,sjdf,j,d;
	for( i=1,k=1,sjdf=0,j,d; k<len-1; ++i )
	{
		// 1st char
		c = str[k++];
		if( sjdf==0 )
		{
			if( (c>=0x80 && c<=0x9f) || (c>=0xe0 && c<=0xe9) ) sjdf=1;
			c = sjtable[c];
		}
		else
		{
			c = sj2table[c];
			sjdf = 0;
		}
		if( c==0xff )return 0;
		d = c * 182;

		// 2nd char
		c = str[k++];
		if( sjdf==0 )
		{
			if( (c>=0x80 && c<=0x9f) || (c>=0xe0 && c<=0xe9) ) sjdf=1;
			c = sjtable[c];
		}
		else
		{
			c = sj2table[c];
			sjdf = 0;
		}
		if( c==0xff )return 0;
		if( (d+=c)>0x7fff )return 0;

		// store to LINE
		if( (j=(i&(8-1)))!=0 )*outbuf |= d << (8 - j) & 0xff;
		*++outbuf = d >> j;
		if( j<7 )*++outbuf = d >> (8 + j);
	}

	// the last char has 7bit data
	c = str[k++];
	if( sjdf==0 )
	{
		if( c>=0xc9 && c<=0xdf )c = c + (0x100 - 0x40) & 0xff;
		c = sjtable[c];
	}
	else
		c = sj2table[c];
	if( c==0xff )return 0;
	*outbuf++ |= c << (8 - i & (8 - 1)) & 0xff;

	return outbuf-start;
}
