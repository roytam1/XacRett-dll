bool CIshTool::GetNextVol()
{
	if( h_Mv==0 || h_FLen==0 )
		return false;

	char *cp;
	int num;
	if( (cp=(char*)strrchr(IshName,'.'))==NULL || !*(cp+1) )
		num = -1;
	else
	{
		cp++;
		num = (cp[1]-'0')*10+(cp[2]-'0');
		if( num<0 || 99<num )
			num = -1;
		if( '0'<=*cp && *cp<='9' )
			num += (*cp-'0')*100;
	}
	num++;
	cp[0]=(num<100)?'i':num/100+'0';
	cp[1]=(num/10)%10+'0';
	cp[2]=   num  %10+'0';
	cp[3]=0;

	fclose( ish );
	if( !(ish = fopen(IshName,"rb")) )
		return false;
	return FindHeader( false );
}

